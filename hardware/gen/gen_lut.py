"""Generate hardware/rtl/tp_lut_rom.sv: the look-up table L[i] = round(-ln((i + 1/2) / 2^U) 2^LF) as a block-RAM ROM
(the -ln u values of the replica-exchange unit, used by pt_top and ptw_top).   python hardware/gen/gen_lut.py [U] [LF]"""
import sys
from pathlib import Path
import numpy as np

U = int(sys.argv[1]) if len(sys.argv) > 1 else 12
LF = int(sys.argv[2]) if len(sys.argv) > 2 else 16
i = np.arange(1 << U, dtype=np.float64)
L = np.rint(-np.log((i + 0.5) / float(1 << U)) * float(1 << LF)).astype(np.int64)
LW = int(L.max()).bit_length()
lines = [f"// Generated by hardware/gen/gen_lut.py (U={U}, LF={LF}); do not edit.",
         f"module tp_lut_rom #(parameter integer U = {U}, parameter integer LW = {LW}) (input wire clk, input wire en, input wire [U-1:0] addr, output reg [LW-1:0] dout);",
         "    (* ram_style = \"block\" *) reg [LW-1:0] mem [0:(1<<U)-1];",
         "    initial begin"]
lines += [f"        mem[{k}] = {LW}'d{int(v)};" for k, v in enumerate(L)]
lines += ["    end", "    always @(posedge clk) if (en) dout <= mem[addr];", "endmodule", ""]
out = Path(__file__).resolve().parents[1] / "rtl" / "tp_lut_rom.sv"
out.write_text("\n".join(lines))
print(out, "LW =", LW)
