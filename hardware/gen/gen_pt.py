"""RTL generator of the one-syndrome-per-shot core: parallel-tempering maximum-likelihood decoder of the rotated surface code (depolarizing code capacity).

Bit-exact with nimbus.decoding.one_shot (the specification). Writes ``pt_core.sv`` with
* ``pt_rep``: one replica. Spins x, z in flip-flops; per move the neuron input dW = #(partner 0, own 0) - #(partner 0, own 1) in narrow
  logic; acceptance dW <= 0 or cmp[lane][dW], where cmp[lane][k] = (u_lane < T[k]) is registered one cycle ahead (the lane uniforms
  do not depend on the state); all moves of the active color flip in the same cycle (one-cycle loop, no stall). Lane uniforms from two
  GFSR trinomial generators (2281/1029, 3217/576) advanced by N = Lmax * B bits per move cycle, two cycles ahead of the move.
  E = popcount(x | z) and the class bits (parity of x on a Z logical, of z on an X logical, relative to the start) in a 2-stage pipeline
  off the loop.
* ``pt_top``: NS replicas, start state c0 = XOR over fired checks of fixed boundary chains, temperature labels and holders, threshold
  table per label, swap unit (per-pair xoshiro128**, -ln u ROM tp_lut_rom, constant per pair, refilled in the background), occupancy
  counters for label 0 over the second half, per-replica best energy, decisions (ML argmax, minimum energy scan), cycle counters.

Timing (cycle t_s = syndrome captured): load t_s + 1, threshold load t_s + 2, first move cycle t_s + 4. A sweep is 6 move cycles; after
a swap sweep G = 6 idle cycles (energy pipeline 3, decision 1, threshold load 1, comparator 1). After the last sweep: 3 cycles to the
last count, 1 cycle ML decision, NS cycles minimum-energy scan.

  python hardware/gen/gen_pt.py --d 5 --NS 8 --B 16 --K 1 --p 0.12 --bmin 0.1 --out out/pt_d5
"""
from __future__ import annotations

import argparse
import os
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]

from nimbus.decoding.one_shot import GFSR_A, GFSR_B, TW_THETA, XIW, PTConfig, build_spec  # noqa: E402

GAP = 4        # idle cycles after a swap sweep (must match the swap pipeline in pt_top.sv)
GAP_CK = 8     # idle cycles after the swap sweep of an early-stop checkpoint (the stop test needs the last count)


def clog2(n: int) -> int:
    return max(1, int(max(n - 1, 0)).bit_length())


def gen_rep(spec, acc: str | None = None) -> str:
    """acc = "mux": per move, dW <= 0 or cmp[lane][dW] (registered comparator bits, a k:1 mux in the loop);
    acc = "thermo": the comparator bits of a lane are a thermometer (T[k] non-increasing in k), so their count c is registered
    instead and a move accepts iff dW <= c (same decision, no mux in the loop). Default from the environment PT_ACC."""
    acc = acc or os.environ.get("PT_ACC", "thermo")
    cfg = spec.cfg
    n, B = spec.n, cfg.B
    cls = spec.cls_mat
    NCL, Lmax = cls.shape
    N = Lmax * B
    supl = [list(dict.fromkeys(int(q) for q in row if q < n)) for row in spec.sup]
    kmax_lane = [max(len(supl[int(r)]) for r in cls[:, j] if r >= 0) for j in range(Lmax)]
    KM = spec.kmax
    EW = clog2(n + 1)
    pa, qa = GFSR_A
    pb, qb = GFSR_B
    lz0 = sorted(int(q) for q in spec.prob.code["lz_all"][0])
    lx0 = sorted(int(q) for q in spec.prob.code["lx_all"][0])
    o = []
    w = o.append
    w("// Generated by hardware/gen/gen_pt.py; do not edit.")
    w(f"// d={spec.d} n={n} moves={spec.R} colors={NCL} Lmax={Lmax} B={B} N={N} kmax={KM}")
    w("module pt_rep (")
    w("    input  wire clk, input wire ld,")
    w(f"    input  wire [{n-1}:0] c0x, input wire [{n-1}:0] c0z, input wire [1:0] cpar,")
    w("    input  wire sd_sh, input wire sd_bit, input wire push_a, input wire push_b, input wire rng_adv,")
    w(f"    input  wire [{KM*B-1}:0] thr_e,     // thresholds of the replica's label (pt_thr: register, or the swap bypass in the load cycle)")
    w(f"    input  wire mv, input wire [{NCL-1}:0] col,")
    w(f"    output reg [{EW-1}:0] E_o, output wire [{EW-1}:0] E_w, output reg [1:0] C_o")
    w(");")
    w(f"    wire [{n-1}:0] x, z;             // clause literals (held in the clause units cl_q<q>)")
    w(f"    reg [{pa-1}:0] ha; reg [{pb-1}:0] hb;")
    w(f"    wire [{N-1}:0] na, nb;")
    for nm, p, q, h in (("na", pa, qa, "ha"), ("nb", pb, qb, "hb")):
        for j in range(N):
            if j < q:
                w(f"    assign {nm}[{j}] = {h}[{j}] ^ {h}[{p - q + j}];")
            else:
                w(f"    assign {nm}[{j}] = {h}[{j}] ^ {h}[{j - q}] ^ {h}[{p - 2 * q + j}];")
    w(f"    reg [{N-1}:0] y, sd;")
    w("    always @(posedge clk) begin")
    w("        // seeding: N bits staged serially in sd, pushed through the same N-bit stride as the generator (no per-bit seed mux)")
    w(f"        if (sd_sh) sd <= {{sd_bit, sd[{N-1}:1]}};")
    w(f"        if (push_a | rng_adv) ha <= {{push_a ? sd : na, ha[{pa-1}:{N}]}};")
    w(f"        if (push_b | rng_adv) hb <= {{push_b ? sd : nb, hb[{pb-1}:{N}]}};")
    w("        if (rng_adv) y <= na ^ nb;")
    w("    end")

    # lane uniforms (first generated bit = MSB) and comparator bank
    for j in range(Lmax):
        bits = ", ".join(f"y[{j * B + b}]" for b in range(B))
        w(f"    wire [{B-1}:0] u{j} = {{{bits}}};")
        if acc == "mux":
            w(f"    reg [{kmax_lane[j]}:1] cmp{j};")
        else:
            cb = clog2(kmax_lane[j] + 1)
            w(f"    wire [{kmax_lane[j]}:1] cmpw{j}; wire [{cb-1}:0] cw{j}; reg [{cb-1}:0] c{j};")
            w(f"    tp_popcnt #(.N({kmax_lane[j]})) uc{j} (.in(cmpw{j}), .cnt(cw{j}));")
    if acc != "mux":
        for j in range(Lmax):
            for k in range(1, kmax_lane[j] + 1):
                w(f"    assign cmpw{j}[{k}] = (u{j} < thr_e[{k * B - 1}:{(k - 1) * B}]);")
    w("    always @(posedge clk) begin")
    for j in range(Lmax):
        if acc == "mux":
            for k in range(1, kmax_lane[j] + 1):
                w(f"        cmp{j}[{k}] <= (u{j} < thr_e[{k * B - 1}:{(k - 1) * B}]);")
        else:
            w(f"        c{j} <= cw{j};")
    w("    end")
    # ---- architecture: clause units, switch fabric (move masks), transition neurons
    if acc != "thermo":
        raise NotImplementedError("only the thermometer acceptance is generated")
    lane_of, col_of = {}, {}
    for k in range(NCL):
        for j in range(Lmax):
            r = int(cls[k, j])
            if r >= 0:
                lane_of[r] = j; col_of[r] = k
    fx = [[] for _ in range(n)]
    fz = [[] for _ in range(n)]
    for r in range(spec.R):
        for q in supl[r]:
            (fx if int(spec.blk[r]) == 0 else fz)[q].append(f"acc{r}")
    w(f"    wire [{n-1}:0] cv, ep, exm, ezm;     // clause outputs: value, energy change for an X flip / Z flip (+1: ep, -1: exm / ezm)")
    w(f"    wire [{n-1}:0] fx, fz;               // switch fabric, neuron -> clause: flip requests on the X / Z port")
    w("    // clause units (one per qubit; the clause x_q OR z_q holds its literals)")
    for q in range(n):
        w(f"    pt_clause cl_q{q} (.clk(clk), .ld(ld), .c0x(c0x[{q}]), .c0z(c0z[{q}]), .fx(fx[{q}]), .fz(fz[{q}]), .x(x[{q}]), "
          f".z(z[{q}]), .v(cv[{q}]), .ep(ep[{q}]), .exm(exm[{q}]), .ezm(ezm[{q}]));")
    w("    // switch fabric, clause -> neuron (one connection per qubit of the move's support) and transition neurons")
    for r in range(spec.R):
        S = supl[r]
        L = len(S)
        b = int(spec.blk[r])
        j, k = lane_of[r], col_of[r]
        cb = clog2(kmax_lane[j] + 1)
        dn = "exm" if b == 0 else "ezm"
        w(f"    wire [{L-1}:0] sw_up_r{r} = {{" + ", ".join(f"ep[{q}]" for q in S) + "};")
        w(f"    wire [{L-1}:0] sw_dn_r{r} = {{" + ", ".join(f"{dn}[{q}]" for q in S) + "};")
        w(f"    wire acc{r};")
        w(f"    pt_neuron #(.L({L}), .CB({cb})) tn_r{r} (.en(mv & col[{k}]), .up(sw_up_r{r}), .dn(sw_dn_r{r}), .c(c{j}), "
          f".acc(acc{r}));     // {'X' if b == 0 else 'Z'} move, color {k}, lane {j}")
    w("    // switch fabric, neuron -> clause")
    for q in range(n):
        w(f"    assign fx[{q}] = " + (" | ".join(fx[q]) if fx[q] else "1'b0") + ";")
        w(f"    assign fz[{q}] = " + (" | ".join(fz[q]) if fz[q] else "1'b0") + ";")
    # energy / class pipeline (2 stages after the state register)
    CH = 32
    nch = (n + CH - 1) // CH
    w(f"    reg [{clog2(CH + 1) - 1}:0] pc [0:{nch-1}];")
    w("    reg c1x, c1z; reg [1:0] cp1;")
    for c in range(nch):
        lo, hi = c * CH, min(n, (c + 1) * CH)
        w(f"    wire [{clog2(hi - lo + 1) - 1}:0] pcw{c}; tp_popcnt #(.N({hi - lo})) upc{c} (.in(cv[{hi-1}:{lo}]), .cnt(pcw{c}));")
    w("    assign E_w = " + " + ".join(f"pc[{c}]" for c in range(nch)) + ";     // energy = number of unsatisfied clauses")
    w("    always @(posedge clk) begin")
    for c in range(nch):
        w(f"        pc[{c}] <= pcw{c};")
    w("        c1x <= ^{" + ", ".join(f"x[{q}]" for q in lz0) + "};")
    w("        c1z <= ^{" + ", ".join(f"z[{q}]" for q in lx0) + "};")
    w("        cp1 <= cpar;")
    w("        E_o <= E_w;")
    w("        C_o <= {c1z ^ cp1[1], c1x ^ cp1[0]};")
    w("    end")
    w("endmodule")
    return "\n".join(o) + "\n", dict(EW=EW, KM=KM, N=N, Lmax=Lmax, NCL=NCL, kmax_lane=kmax_lane)


def gen_consts(spec, rinfo):
    """pt_c0 (syndrome -> start state and class constants), pt_thr_rom (label -> thresholds), pt_theta_rom, pt_params.svh."""
    cfg = spec.cfg
    n, NS, B, K = spec.n, cfg.NS, cfg.B, cfg.K
    EW, KM, NCL = rinfo["EW"], rinfo["KM"], rinfo["NCL"]
    m0 = spec.chains[0].shape[0]
    m = m0 + spec.chains[1].shape[0]
    LW = clog2(NS)
    lz0 = sorted(int(q) for q in spec.prob.code["lz_all"][0])
    lx0 = sorted(int(q) for q in spec.prob.code["lx_all"][0])
    TW = TW_THETA
    SH = cfg.LF + cfg.TF
    o = []
    w = o.append
    w("// Generated by hardware/gen/gen_pt.py; do not edit.")
    w(f"// d={spec.d} p={spec.p} NS={NS} bmin={cfg.bmin} K={K} B={B} USW={cfg.USW}")
    w(f"module pt_c0 (input wire [{m-1}:0] sr, output wire [{n-1}:0] c0x, output wire [{n-1}:0] c0z, output wire [1:0] cpar);")
    for nm, ch, off in (("c0x", spec.chains[0], 0), ("c0z", spec.chains[1], m0)):
        for q in range(n):
            js = np.flatnonzero(ch[:, q])
            w(f"    assign {nm}[{q}] = " + (" ^ ".join(f"sr[{off + int(j)}]" for j in js) if len(js) else "1'b0") + ";")
    w("    assign cpar = {^{" + ", ".join(f"c0z[{q}]" for q in lx0) + "}, ^{" + ", ".join(f"c0x[{q}]" for q in lz0) + "}};")
    w("endmodule")
    # Thresholds and swap constants are runtime registers (pt_thr per replica, theta per pair in pt_top), written over AXI.
    # Their power-on values (THR_INIT, THETA_INIT) are the tables of the generation p; the host normally overwrites them.
    thr_init = 0
    for t in range(NS - 1, -1, -1):
        for k in range(KM, 0, -1):
            thr_init = (thr_init << B) | int(spec.thr[t, k])
    th_init = 0
    for t in range(max(NS - 1, 1) - 1, -1, -1):
        th_init = (th_init << TW) | (int(spec.theta_sw[t]) if t < NS - 1 else 0)
    prm = [f"localparam integer NS = {NS}, NP = {max(NS - 1, 1)}, N = {n}, M = {m}, EW = {EW}, KM = {KM}, B = {B}, LW = {LW};",
           f"localparam integer NCL = {NCL}, KSW = {K}, GAP = {GAP}, GAP_CK = {GAP_CK}, USW = {cfg.USW}, TW = {TW}, SH = {SH}, XIW = {XIW};",
           f"localparam integer KMB = {KM * B}, LMAX = {rinfo['Lmax']}, NLB = {rinfo['N']};",
           f"localparam [{XIW-1}:0] XIMAX = {XIW}'d{(1 << XIW) - 1};",
           f"localparam [{NS * KM * B - 1}:0] THR_INIT = {NS * KM * B}'h{thr_init:x};      // p = {spec.p}: row t = label t, k = 1 at the LSB",
           f"localparam [{max(NS - 1, 1) * TW - 1}:0] THETA_INIT = {max(NS - 1, 1) * TW}'h{th_init:x};"]
    return "\n".join(o) + "\n", "`ifndef PT_PARAMS_SVH\n`define PT_PARAMS_SVH\n" + "\n".join(prm) + "\n`endif\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--d", type=int, required=True); ap.add_argument("--p", type=float, default=0.12)
    ap.add_argument("--NS", type=int, default=8); ap.add_argument("--bmin", type=float, default=0.1)
    ap.add_argument("--K", type=int, default=1); ap.add_argument("--B", type=int, default=16)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    spec = build_spec(a.d, a.p, PTConfig(NS=a.NS, bmin=a.bmin, K=a.K, B=a.B))
    rep, rinfo = gen_rep(spec)
    cons, prm = gen_consts(spec, rinfo)
    out = Path(a.out); out.mkdir(parents=True, exist_ok=True)
    (out / "pt_core.sv").write_text(rep + "\n" + cons)
    (out / "pt_params.svh").write_text(prm)
    m = spec.chains[0].shape[0] + spec.chains[1].shape[0]
    info = dict(spec.info, **rinfo, NS=a.NS, K=a.K, B=a.B, p=a.p, bmin=a.bmin, GAP=GAP, TW=TW_THETA, M_syn=m,
                USW=spec.cfg.USW, LF=spec.cfg.LF, TF=spec.cfg.TF, XIW=XIW, d=a.d)
    (out / "pt_info.json").write_text(json.dumps(info, indent=1, default=int))
    print(json.dumps({k: info[k] for k in ("n", "R", "Lmax", "N", "KM", "EW")}))
    return spec


if __name__ == "__main__":
    main()
